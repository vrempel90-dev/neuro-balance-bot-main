"""Durable Wazzup ingress: acknowledge storage, process outside the HTTP request.

Only one application instance may own this SQLite inbox. A restarting instance
resumes *pending* jobs, but quarantines interrupted processing: a CRM or Wazzup
request may already have succeeded remotely. Such jobs must be reconciled rather
than blindly replayed. Provider-specific idempotency remains in the processor.
"""
from __future__ import annotations

import asyncio
from contextlib import suppress
import hashlib
import json
import time
from datetime import datetime, timedelta, timezone
from typing import Any, Awaitable, Callable

import state


_DDL = """
CREATE TABLE IF NOT EXISTS webhook_inbox (
    sequence INTEGER PRIMARY KEY AUTOINCREMENT,
    job_id TEXT NOT NULL UNIQUE,
    chat_id TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending',
    payload_json TEXT NOT NULL,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    started_at TEXT,
    error_type TEXT NOT NULL DEFAULT '',
    attempts INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_webhook_inbox_status
    ON webhook_inbox(status, sequence);
CREATE INDEX IF NOT EXISTS idx_webhook_inbox_chat
    ON webhook_inbox(chat_id, sequence);
"""
_TERMINAL_STATUSES = {"done", "failed", "uncertain"}


def init_db() -> None:
    with state._connect() as conn:
        conn.executescript(_DDL)


def enqueue(
    *, message_key: str, chat_id: str, payload: dict[str, Any],
    raw_msg: dict[str, Any], parse_meta: dict[str, Any],
) -> dict[str, Any]:
    """Commit a unique incoming delivery before the caller sends HTTP 200.

    The caller must scope message_key to channel/chat/provider message ID. For a
    delivery without a provider ID, use a deterministic hash of its raw message.
    Do not use timestamps generated by the receiver: retries would become new
    jobs. The ingress payload remains in the access-controlled application DB,
    never in diagnostic output.
    """
    if not str(message_key or "").strip() or not str(chat_id or "").strip():
        raise ValueError("stable message key and chat id are required")
    body = json.dumps(
        {"payload": payload, "raw_msg": raw_msg, "parse_meta": parse_meta},
        ensure_ascii=False, separators=(",", ":"),
    )
    if len(body.encode("utf-8")) > 2 * 1024 * 1024:
        raise ValueError("inbox message exceeds size limit")
    job_id = hashlib.sha256(str(message_key).encode("utf-8")).hexdigest()
    stamp = state.now_iso()
    init_db()
    with state._connect() as conn:
        cursor = conn.execute(
            "INSERT OR IGNORE INTO webhook_inbox "
            "(job_id,chat_id,payload_json,created_at,updated_at) VALUES (?,?,?,?,?)",
            (job_id, str(chat_id), body, stamp, stamp),
        )
        duplicate = cursor.rowcount == 0
        row = conn.execute(
            "SELECT status FROM webhook_inbox WHERE job_id=?", (job_id,),
        ).fetchone()
    return {"accepted": True, "duplicate": duplicate, "job_id": job_id, "status": row["status"]}


def recover_interrupted() -> int:
    """Quarantine jobs interrupted by a process restart; never replay them."""
    init_db()
    with state._connect() as conn:
        cursor = conn.execute(
            "UPDATE webhook_inbox SET status='uncertain', error_type='ProcessInterrupted', "
            "updated_at=? WHERE status='processing'", (state.now_iso(),),
        )
    if cursor.rowcount:
        state.log_event("inbox", "inbox_interrupted_processing_warning", {"count": cursor.rowcount})
    return cursor.rowcount


def claim_next() -> dict[str, Any] | None:
    """Claim one FIFO job atomically, never overtaking its own chat's job."""
    with state._connect() as conn:
        conn.execute("BEGIN IMMEDIATE")
        row = conn.execute(
            "SELECT j.* FROM webhook_inbox j WHERE j.status='pending' AND NOT EXISTS ("
            " SELECT 1 FROM webhook_inbox previous WHERE previous.chat_id=j.chat_id "
            " AND previous.sequence<j.sequence AND previous.status IN ('pending','processing','uncertain')"
            ") ORDER BY j.sequence LIMIT 1",
        ).fetchone()
        if row is None:
            return None
        stamp = state.now_iso()
        conn.execute(
            "UPDATE webhook_inbox SET status='processing', started_at=?, updated_at=?, "
            "attempts=attempts+1 WHERE job_id=? AND status='pending'",
            (stamp, stamp, row["job_id"]),
        )
    body = json.loads(row["payload_json"])
    return {"job_id": row["job_id"], "chat_id": row["chat_id"], **body}


def finish(job_id: str, status: str = "done", *, error_type: str = "") -> None:
    if status not in _TERMINAL_STATUSES:
        raise ValueError("invalid inbox terminal status")
    # A successful job no longer needs a duplicate copy of the sensitive body.
    # Keep its stable key for deduplication; failed/uncertain jobs retain their
    # body for authorized reconciliation and are never auto-retried.
    with state._connect() as conn:
        conn.execute(
            "UPDATE webhook_inbox SET status=?,updated_at=?,error_type=?, "
            "payload_json=CASE WHEN ?='done' THEN '{}' ELSE payload_json END "
            "WHERE job_id=? AND status='processing'",
            (status, state.now_iso(), str(error_type)[:80], status, str(job_id)),
        )


def resolve_uncertain(job_id: str, *, resolution: str) -> bool:
    """Release a quarantined chat only after an operator reconciles the job.

    This is deliberately not an automatic retry or a public endpoint. The
    authorized caller must verify the remote CRM/message outcome first. Mark
    done when reconciled as completed; failed when safely determined not to
    have completed. Neither resolution replays the original job.
    """
    if resolution not in {"done", "failed"}:
        raise ValueError("uncertain jobs require a final reconciliation")
    with state._connect() as conn:
        cursor = conn.execute(
            "UPDATE webhook_inbox SET status=?,updated_at=?, "
            "payload_json=CASE WHEN ?='done' THEN '{}' ELSE payload_json END "
            "WHERE job_id=? AND status='uncertain'",
            (resolution, state.now_iso(), resolution, str(job_id)),
        )
    return cursor.rowcount == 1


def purge_completed(*, retention_days: int = 7) -> int:
    """Bound duplicate-key retention without deleting unresolved jobs."""
    threshold = (datetime.now(timezone.utc) - timedelta(days=max(1, retention_days))).isoformat()
    with state._connect() as conn:
        cursor = conn.execute(
            "DELETE FROM webhook_inbox WHERE status='done' AND updated_at<?", (threshold,),
        )
    return cursor.rowcount


def status_summary() -> dict[str, Any]:
    """Return aggregate operational metrics, never chat IDs or message text."""
    init_db()
    with state._connect() as conn:
        rows = conn.execute("SELECT status,COUNT(*) AS count FROM webhook_inbox GROUP BY status").fetchall()
        oldest = conn.execute(
            "SELECT MIN(created_at) AS created_at FROM webhook_inbox WHERE status='pending'",
        ).fetchone()["created_at"]
        quarantined = conn.execute(
            "SELECT COUNT(DISTINCT chat_id) AS count FROM webhook_inbox WHERE status='uncertain'",
        ).fetchone()["count"]
        blocked = conn.execute(
            "SELECT COUNT(*) AS count FROM webhook_inbox j WHERE j.status='pending' AND EXISTS ("
            " SELECT 1 FROM webhook_inbox previous WHERE previous.chat_id=j.chat_id "
            " AND previous.sequence<j.sequence AND previous.status='uncertain')",
        ).fetchone()["count"]
    counts = {status: 0 for status in ("pending", "processing", "done", "failed", "uncertain")}
    counts.update({row["status"]: row["count"] for row in rows})
    age = max(0.0, (datetime.now(timezone.utc) - datetime.fromisoformat(oldest)).total_seconds()) if oldest else 0.0
    return {
        "counts": counts, "oldest_pending_seconds": round(age, 1),
        "quarantined_chats": quarantined, "pending_blocked_by_uncertain": blocked,
    }


Processor = Callable[[dict[str, Any]], Awaitable[dict[str, Any] | None]]


class InboxWorker:
    """A bounded in-process worker backed by the persistent inbox.

    Railway must run exactly one replica / one Uvicorn worker for this SQLite
    implementation. Different chats can progress concurrently; same-chat FIFO
    is guaranteed by claim_next and the application's complete-turn lock.
    """
    def __init__(
        self, processor: Processor, *, concurrency: int = 4,
        poll_seconds: float = 0.25, job_timeout: float = 180.0,
    ) -> None:
        self.processor = processor
        self.concurrency = max(1, min(8, int(concurrency)))
        self.poll_seconds = max(0.05, float(poll_seconds))
        self.job_timeout = max(0.1, float(job_timeout))
        self._task: asyncio.Task[None] | None = None
        self._active: set[asyncio.Task[None]] = set()
        self._stopping = False
        self._last_heartbeat = 0.0
        self._last_purge = 0.0

    def start(self) -> asyncio.Task[None]:
        if self._task is not None and not self._task.done():
            return self._task
        # Called only by the sole app instance after state.init_db().
        recover_interrupted()
        self._stopping = False
        self._task = asyncio.create_task(self._run(), name="neuro-durable-webhook-inbox")
        return self._task

    async def stop(self, *, timeout: float = 10.0) -> None:
        self._stopping = True
        if self._task is None:
            return
        try:
            await asyncio.wait_for(asyncio.shield(self._task), timeout=max(0.1, timeout))
        except asyncio.TimeoutError:
            self._task.cancel()
            for task in tuple(self._active):
                task.cancel()
            await asyncio.gather(*self._active, return_exceptions=True)
            with suppress(asyncio.CancelledError):
                await self._task

    def status(self) -> dict[str, Any]:
        return {
            "running": bool(self._task is not None and not self._task.done() and not self._stopping),
            "active_jobs": len(self._active),
            "heartbeat_age_seconds": round(time.monotonic() - self._last_heartbeat, 1) if self._last_heartbeat else None,
            **status_summary(),
        }

    async def _process(self, job: dict[str, Any]) -> None:
        job_id = job["job_id"]
        chat_id = job["chat_id"]
        try:
            result = await asyncio.wait_for(self.processor(job), timeout=self.job_timeout)
            if not isinstance(result, dict):
                raise TypeError("inbox processor must return an explicit result")
            explicit = result.get("inbox_status")
            reason = str(result.get("no_reply_reason") or "")
            if explicit in _TERMINAL_STATUSES:
                status = str(explicit)
            elif reason in {"send_failed", "send_uncertain", "delivery_uncertain"}:
                status = "uncertain"
            elif reason in {"crm_lookup_failed", "processing_failed"} or result.get("ok") is False:
                status = "failed"
            else:
                status = "done"
            finish(job_id, status, error_type=reason if status != "done" else "")
            state.log_event(chat_id, "inbox_job_finished", {"status": status, "job_id": job_id})
        except asyncio.CancelledError:
            finish(job_id, "uncertain", error_type="ProcessingCancelled")
            state.log_event(chat_id, "inbox_processing_cancelled_warning", {"job_id": job_id})
            raise
        except Exception as exc:
            # Any exception could follow a successful but unacknowledged side
            # effect. Quarantine it; never retry the entire conversation turn.
            finish(job_id, "uncertain", error_type=type(exc).__name__)
            state.log_event(chat_id, "inbox_processing_failed", {"job_id": job_id, "error_type": type(exc).__name__})

    async def _run(self) -> None:
        try:
            while not self._stopping:
                self._last_heartbeat = time.monotonic()
                for task in tuple(self._active):
                    if task.done():
                        self._active.discard(task)
                        # Retrieve exceptions (e.g. a database failure while
                        # saving terminal state), keeping them observable.
                        if not task.cancelled() and task.exception() is not None:
                            state.log_event("inbox", "inbox_task_failed", {"error_type": type(task.exception()).__name__})
                try:
                    if self._last_heartbeat - self._last_purge >= 3600:
                        purge_completed()
                        self._last_purge = self._last_heartbeat
                    while len(self._active) < self.concurrency and not self._stopping:
                        job = claim_next()
                        if job is None:
                            break
                        self._active.add(asyncio.create_task(self._process(job)))
                except Exception as exc:
                    # A short storage failure must not permanently kill the
                    # queue consumer. No processing job is retried here.
                    state.log_event("inbox", "inbox_poll_failed", {"error_type": type(exc).__name__})
                    await asyncio.sleep(max(1.0, self.poll_seconds))
                await asyncio.sleep(self.poll_seconds)
        finally:
            if self._active:
                await asyncio.gather(*self._active, return_exceptions=True)
