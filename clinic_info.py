def get_clinic_info(topic: str, lang: str | None = None) -> str | None:
    """Возвращает операторский шаблон темы на нужном языке.

    Для lang="kk" отдаём утверждённый казахский текст. Если казахского
    варианта для темы нет — возвращаем русский, но НИКОГДА не переводим
    его на лету: выдуманный казахский текст опаснее русского.
    """
    if (lang or "").lower() == "kk":
        kk = CLINIC_INFO_TEMPLATES_KK.get(topic)
        if kk:
            return kk
    return CLINIC_INFO_TEMPLATES.get(topic)


def has_kazakh_template(topic: str) -> bool:
    return topic in CLINIC_INFO_TEMPLATES_KK


def topics() -> list[str]:
    return list(CLINIC_INFO_TEMPLATES.keys())
